#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const tableMapPath = path.join(__dirname, "supabase-table-map.json");
const tableMap = JSON.parse(fs.readFileSync(tableMapPath, "utf8"));

const tableColumns = {
  projects: [
    "id", "title", "slug", "short_description", "detailed_description", "project_type", "project_status",
    "location", "city", "district", "start_year", "delivery_year", "land_area", "construction_area",
    "apartment_count", "floor_count", "block_count", "cover_image_url", "is_featured", "is_published",
    "sort_order", "seo_title", "seo_description", "created_at", "updated_at",
  ],
  project_images: ["id", "project_id", "image_url", "thumbnail_url", "title", "alt_text", "sort_order", "created_at"],
  media_library: ["id", "image_url", "thumbnail_url", "file_name", "title", "alt_text", "related_project_id", "created_at"],
  site_settings: [
    "id", "company_name", "phone", "whatsapp_number", "email", "address", "map_embed_url", "instagram_url",
    "facebook_url", "linkedin_url", "footer_description", "hero_title", "hero_subtitle", "whatsapp_message",
    "seo_title", "seo_description", "updated_at",
  ],
  contact_requests: ["id", "full_name", "phone", "email", "service_type", "message", "status", "created_at"],
  customers: [
    "id", "customer_type", "full_name", "company_name", "phone", "whatsapp", "email", "tax_or_identity_number",
    "address", "city", "district", "status", "notes", "created_at", "updated_at",
  ],
  customer_projects: ["id", "customer_id", "project_id", "created_at"],
  payment_plans: ["id", "customer_id", "project_id", "title", "description", "amount", "due_date", "status", "notes", "created_at", "updated_at"],
  payments: ["id", "customer_id", "project_id", "payment_plan_id", "amount", "payment_date", "payment_method", "description", "document_url", "created_at", "updated_at"],
  expenses: ["id", "project_id", "customer_id", "title", "category", "amount", "expense_date", "description", "document_url", "created_at", "updated_at"],
  customer_notes: ["id", "customer_id", "note", "created_at"],
  documents: ["id", "customer_id", "project_id", "title", "document_type", "file_url", "notes", "created_at"],
  notifications: ["id", "title", "message", "type", "priority", "related_customer_id", "related_project_id", "related_payment_plan_id", "is_read", "created_at"],
  employees: ["id", "full_name", "phone", "role", "notes", "status", "created_at", "updated_at"],
  expense_cards: ["id", "name", "category", "description", "status", "created_at", "updated_at"],
  financial_entries: [
    "id", "project_id", "entry_date", "card_type", "customer_id", "employee_id", "expense_card_id", "title",
    "description", "amount", "currency_tag", "group_tag", "direction", "status", "document_url", "created_at", "updated_at",
  ],
  cookie_consents: ["id", "consent_status", "necessary", "analytics", "marketing", "user_agent", "created_at"],
  profiles: ["id", "user_id", "email", "display_name", "created_at"],
  user_roles: ["id", "user_id", "role", "created_at"],
};

const booleanColumns = new Set([
  "is_featured", "is_published", "is_read", "is_active", "necessary", "analytics", "marketing",
]);

const dateTimeColumns = new Set(["created_at", "updated_at"]);
const dateColumns = new Set(["due_date", "payment_date", "expense_date", "entry_date"]);
const skipSourceTables = new Set(["admin_users"]);

const args = parseArgs(process.argv.slice(2));
if (!args.input || !args.output) {
  console.error("Usage: node migration-tools/convert-supabase-json-to-mysql.mjs --input <file-or-folder> --output <file.sql> [--include-demo]");
  process.exit(1);
}

const warnings = [];
const tables = loadInput(args.input);
const sql = [];

sql.push("-- Generated by migration-tools/convert-supabase-json-to-mysql.mjs");
sql.push("-- Review before importing. Do not commit generated SQL containing production data.");
sql.push("SET NAMES utf8mb4;");
sql.push("SET FOREIGN_KEY_CHECKS = 0;");

for (const [sourceTable, targetTable] of Object.entries(tableMap)) {
  if (skipSourceTables.has(sourceTable)) continue;

  const rows = tables[sourceTable];
  if (!Array.isArray(rows)) {
    warnings.push(`No rows found for ${sourceTable}; skipped.`);
    continue;
  }

  const columns = tableColumns[sourceTable];
  if (!columns) {
    warnings.push(`No column map for ${sourceTable}; skipped.`);
    continue;
  }

  let imported = 0;
  for (const originalRow of rows) {
    if (!originalRow || typeof originalRow !== "object" || Array.isArray(originalRow)) {
      warnings.push(`Skipped malformed row in ${sourceTable}.`);
      continue;
    }

    if (!args.includeDemo && isDemoRow(originalRow)) {
      continue;
    }

    const row = normalizeRow(sourceTable, originalRow, columns, warnings);
    sql.push(buildUpsert(targetTable, columns, row));
    imported++;
  }

  warnings.push(`${sourceTable} -> ${targetTable}: generated ${imported} upsert statements.`);
}

sql.push("SET FOREIGN_KEY_CHECKS = 1;");

const outputBody = [
  "-- Warnings / summary:",
  ...warnings.map((warning) => `-- - ${warning}`),
  "",
  ...sql,
  "",
].join("\n");

fs.mkdirSync(path.dirname(path.resolve(args.output)), { recursive: true });
fs.writeFileSync(args.output, outputBody, "utf8");
console.log(`Wrote ${args.output}`);
console.log(`${warnings.length} warnings/summary lines written as SQL comments.`);

function parseArgs(argv) {
  const parsed = { includeDemo: false };
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (arg === "--include-demo") {
      parsed.includeDemo = true;
    } else if (arg === "--input") {
      parsed.input = argv[++index];
    } else if (arg === "--output") {
      parsed.output = argv[++index];
    }
  }
  return parsed;
}

function loadInput(inputPath) {
  const resolved = path.resolve(inputPath);
  const stat = fs.statSync(resolved);
  if (stat.isDirectory()) {
    const result = {};
    for (const sourceTable of Object.keys(tableMap)) {
      const file = path.join(resolved, `${sourceTable}.json`);
      if (fs.existsSync(file)) {
        result[sourceTable] = readJson(file);
      }
    }
    return result;
  }

  const payload = readJson(resolved);
  if (payload?.schema && payload.schema !== "akinal-full-supabase-export-v1" && payload.schema !== "akinal-projects-export-v1") {
    warnings.push(`Unrecognized schema "${payload.schema}"; continuing with table detection.`);
  }
  return payload.data && typeof payload.data === "object" ? payload.data : payload;
}

function readJson(file) {
  const payload = JSON.parse(fs.readFileSync(file, "utf8"));
  return payload;
}

function normalizeRow(sourceTable, originalRow, columns, warningsList) {
  const row = {};
  for (const column of columns) {
    let value = originalRow[column] ?? null;

    if (booleanColumns.has(column)) {
      value = normalizeBoolean(value);
    } else if (dateTimeColumns.has(column)) {
      value = normalizeDateTime(value);
    } else if (dateColumns.has(column)) {
      value = normalizeDate(value);
    } else if (typeof value === "object" && value !== null) {
      value = JSON.stringify(value);
    }

    if (["cover_image_url", "image_url", "thumbnail_url", "document_url", "file_url"].includes(column)) {
      value = normalizePathValue(sourceTable, column, value, originalRow, warningsList);
    }

    row[column] = value;
  }
  return row;
}

function normalizeBoolean(value) {
  if (value === true) return 1;
  if (value === false || value === null || value === undefined) return 0;
  if (typeof value === "number") return value === 1 ? 1 : 0;
  return ["1", "true", "yes", "evet"].includes(String(value).toLowerCase()) ? 1 : 0;
}

function normalizeDateTime(value) {
  if (!value) return null;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  return date.toISOString().slice(0, 19).replace("T", " ");
}

function normalizeDate(value) {
  if (!value) return null;
  const text = String(value);
  if (/^\d{4}-\d{2}-\d{2}$/.test(text)) return text;
  const date = new Date(text);
  if (Number.isNaN(date.getTime())) return null;
  return date.toISOString().slice(0, 10);
}

function normalizePathValue(sourceTable, column, value, row, warningsList) {
  if (typeof value !== "string" || value.trim() === "") return null;
  const trimmed = value.trim();
  if (trimmed.startsWith("/src/assets/")) {
    warningsList.push(`${sourceTable}.${column} for row ${row.id ?? row.slug ?? "unknown"} used ${trimmed}; converted to NULL.`);
    return null;
  }
  if (trimmed.includes("supabase.co/storage/v1/object/public/")) {
    warningsList.push(`${sourceTable}.${column} for row ${row.id ?? row.slug ?? "unknown"} is a Supabase Storage URL and must be rewritten to /uploads/... after storage export.`);
  }
  return trimmed;
}

function isDemoRow(row) {
  return Object.values(row).some((value) => typeof value === "string" && value.startsWith("DEMO_DATA_"));
}

function buildUpsert(targetTable, columns, row) {
  const quotedColumns = columns.map((column) => `\`${column}\``).join(", ");
  const values = columns.map((column) => sqlValue(row[column])).join(", ");
  const updates = columns
    .filter((column) => column !== "id")
    .map((column) => `\`${column}\` = VALUES(\`${column}\`)`)
    .join(", ");
  return `INSERT INTO \`${targetTable}\` (${quotedColumns}) VALUES (${values}) ON DUPLICATE KEY UPDATE ${updates};`;
}

function sqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  return `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}
